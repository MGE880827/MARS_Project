# 掛載外部依賴
import re

"""
[名稱] 車輛領域之字元辨識配置字典 (Vehicle Domain Character OCR Rules)
[作用] 定義車輛領域主階目標 (VEH-車身標記) 與次階目標 (LIC-車牌號碼) 之光學字元正規化規範，涵蓋特徵標籤識別、裝飾雜訊過濾、字元白名單過濾以及單行格式合格性驗證。
"""
# ==========================================================================================
# < 字典配置說明表 >
# 1. force_upper       : [bool]       字串大小寫標準化開關 (True: 強制轉為大寫英數，False: 保留原始大小寫)
# 2. default_attr      : [str]        特徵標籤基準回退值 (未匹配任何特徵模式時指派之預設屬性標籤)
# 3. attr_patterns     : [list]       特徵屬性識別清單，定義 [(特徵屬性名稱, [觸發關鍵字清單])] 之匹配規則
# 4. noise_tokens      : [list]       干擾雜訊過濾清單，包含裝飾符號、主管機關地名與排版標點，於純化階段主動剔除
# 5. whitelist_regex   : [re.Pattern] 有效字元保留白名單反向正則表示式 (用於剔除所有非合法定義之字元)
# 6. target_regex      : [re.Pattern] 標準格式正規驗證表示式 (用於判定單行字串是否已完全符合目標編碼格式)
# 7. prefix_supp_regex : [re.Pattern] 連續重複前綴抑制正則表達式 (用於消除如 "軍軍C1234" 之重複噪點)
# ==========================================================================================

_VEH_CHAR_SCHEMA = {
    # =============================================
    # ｜INFER｜REGEX-001｜主領域｜VEH-車輛領域
    # =============================================
    "force_upper"       : True,
    "default_attr"      : "STANDARD",
    "attr_patterns"     : [],
    "noise_tokens"      : ["-", "—", "•", "·", " "],
    "whitelist_regex"   : re.compile(r"[^A-Z0-9\u4e00-\u9fa5]"),         # 車身允許繁體中文與英數
    "target_regex"      : re.compile(r"^[A-Z0-9\u4e00-\u9fa5]{2,12}$"),
    "prefix_supp_regex" : None
}

_LIC_CHAR_SCHEMA = {
    # =============================================
    # ｜INFER｜REGEX-002｜次領域｜LIC-車牌領域
    # =============================================
    "force_upper"       : True,
    "default_attr"      : "一般",
    "attr_patterns"     : [
        ("電動車", ["電動車", "電動"]),
        ("軍車",   ["軍"]),
        ("特種車", ["特種"]),
        ("試車牌", ["試"]),
        ("外交車", ["使", "領", "外"]),
        ("臨時車", ["臨"])
    ],
    "noise_tokens"      : [
        "軍用車輛", "軍用", "國軍", "電動車", "電動", 
        "TAIWAN", "臺灣省", "台灣省", "台北市", "臺北市", "高雄市", "特種",
        "-", "—", "•", "·", "點", " "
    ],
    "whitelist_regex"   : re.compile(r"[^A-Z0-9軍試使領外臨]"),
    "target_regex"      : re.compile(r"^(?:[軍試使領外臨][A-Z0-9]{2,6}|(?=.*[0-9])[A-Z0-9]{4,8})$"),
    "prefix_supp_regex" : re.compile(r"^([軍試使領外臨])\1+")
}

# =============================================
# ⭐｜模組導出｜字元辨識規則字典
# =============================================
CHAR_RULES = {
    "VEH" : _VEH_CHAR_SCHEMA,   # 支援以主領域 "VEH" 查詢
    "LIC" : _LIC_CHAR_SCHEMA    # 支援以次領域 "LIC" 查詢
}

__all__ = ["CHAR_RULES"]